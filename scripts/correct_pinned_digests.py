"""Correct a file that records checksums of other files, under one human step.

Some artifacts cannot be regenerated by their own writer -- the AST attestation
baseline has no multi-symbol repair path, and the install lockfile's only writer
refuses when the file already exists.  Correcting them has therefore been done
by a throwaway script each time, written fresh, run once, discarded.  The same
two corrections were written from scratch three times before this file existed.
That leaves the operator with no tool and a standing dependency on whoever wrote
the script -- and it means the agent that composed the instructions is, through
a human relay, blessing its own verifier.

**This tool exists so the operator's part is one act they can actually perform:
read a plan, and type a checksum.**

Why the checksum is not theatre
-------------------------------
The two digests compared are separated in *time*, not merely printed twice:

1. the plan is derived from the tree, displayed, and digested  -> ``A``
2. the operator reads the plan and types the first 8 characters of ``A``
3. the plan is **re-derived from the tree** and digested       -> ``B``
4. ``A != B`` refuses, having written nothing

So the typed digest binds the operator's authorization to the exact state they
read.  A tree that moved in between -- another session committing, an editor
saving -- is caught rather than silently blessed.  This is the check/use gap
that `AGENTS.md` names on the interpreter trust root, closed here by
measurement rather than assumed away.

BLOCKED -- DO NOT USE
---------------------
An External Security Review (Codex, 2026-08-27,
``dev/reviews/2026-08-27-external-security-review-correct-pinned-digests.md``)
returned **BLOCK** with seven blocking findings, two of them CRITICAL, each
reproduced rather than argued.  The two that matter most:

* ``--authorize`` lets any process perform the act this file called human
  authorization, and removing the flag would not fix it -- an agent can
  allocate a pseudo-terminal.  Same OS user, same shell, no identity signal.
* The plan digest does **not** bind the complete preimage or output.  The
  reviewer built two states with the same record count and the same
  add/remove set, changed a *kept* record and a top-level field between
  derivations, and got **identical digests** -- then apply wrote the changes
  the operator never authorized.

So this module's central claim, that the checksum is not theatre, was
overstated.  The A/B comparison is real but narrow: it detects a mutation only
where that mutation changes the plan's projection.

``main()`` refuses on entry until the redesign in the review's final section
lands.  The refusal is in code, not in a comment, because a warning nobody
executes is how a blocked tool gets used anyway.

What this tool is not
---------------------
It is not the gate-anchor ceremony.  That one signs, and its irreducible human
act is making a key available, which no script may do.

**"Re-anchor" names both operations in this repository, and that is why this
file is not called one.**  Rewriting a pinned fixture -- what happens here --
moves no ref, holds no key, and produces no signature.  Moving
``refs/cairn/gate-anchor`` is a two-stage signing ceremony in ``reanchor.sh``.
A file named for the shared word would sit one letter from the ceremony that
signs, and the wrong one would eventually be reached for.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BASELINE = REPO / 'bootstrap/tests/fixtures/scaffold_ast_baseline.json'
LOCKFILE = REPO / 'dev/.cairn/cairn-lock.yml'


# --------------------------------------------------------------------------
# shared helpers

def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(['git', *args], cwd=REPO,
                          capture_output=True, text=True)


def _tracked(rel: str) -> bool:
    return _git('ls-files', '--error-unmatch', rel).returncode == 0


class Refusal(Exception):
    """A precondition failed.  Nothing is written and nothing is guessed."""


# --------------------------------------------------------------------------
# correction: the AST attestation baseline

def _strip_docstrings(node: ast.AST) -> ast.AST:
    for sub in ast.walk(node):
        body = getattr(sub, 'body', None)
        if isinstance(sub, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef,
                            ast.ClassDef)) and body:
            first = body[0]
            if (isinstance(first, ast.Expr)
                    and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                sub.body = body[1:] or [ast.Pass()]
    return node


def _symbol_at(rev: str, relpath: str, kind: str, name: str) -> str | None:
    """The symbol's executable AST at *rev*, docstrings stripped, or None."""
    blob = _git('show', f'{rev}:{relpath}')
    if blob.returncode != 0:
        return None
    try:
        tree = ast.parse(blob.stdout)
    except SyntaxError:
        return None
    for node in tree.body:
        got = getattr(node, 'name', None)
        node_kind = type(node).__name__
        if got is None:
            if isinstance(node, ast.Assign) and node.targets:
                got = getattr(node.targets[0], 'id', None)
            elif isinstance(node, ast.AnnAssign):
                got = getattr(node.target, 'id', None)
            # `_ast_attest` keys Assign and AnnAssign alike under "Assign:",
            # so the key's own kind cannot tell them apart.
            if node_kind == 'AnnAssign':
                node_kind = 'Assign'
        if got == name and node_kind == kind:
            return ast.dump(_strip_docstrings(node), include_attributes=False)
    return None


def plan_ast_baseline() -> list[dict]:
    sys.path.insert(0, str(REPO / 'bootstrap' / 'tests'))
    import _ast_attest as A                                  # noqa: PLC0415

    dirty = _git('status', '--porcelain', '--', 'bootstrap/_scaffold/').stdout.strip()
    if dirty:
        raise Refusal(
            'bootstrap/_scaffold/ has uncommitted changes. The digests would '
            'come from the working tree while the nature check reads committed '
            f'revisions, so they could disagree:\n{dirty}')

    baseline = json.loads(BASELINE.read_text(encoding='utf-8'))
    modules = sorted((REPO / 'bootstrap/_scaffold').glob('*.py'))
    merged, _ = A._merge_current(modules)
    _problems, changed, missing, dup, _new = A._classify(baseline, merged)
    if missing or dup:
        raise Refusal(f'MISSING={sorted(missing)} DUPLICATE={sorted(dup)} -- '
                      'a symbol left the package or single-source broke. That '
                      'is a review item, not a re-anchor.')

    anchor = _git('log', '-1', '--format=%H', '--',
                  'bootstrap/tests/fixtures/scaffold_ast_baseline.json').stdout.strip()
    rows: list[dict] = []
    for key in sorted(changed):
        kind, _, name = key.partition(':')
        entries = merged[key]
        if len(entries) > 1:
            raise Refusal(f'{key} resolves to {len(entries)} modules')
        new_digest, module = entries[0]
        rel = Path(module)
        rel = (rel.relative_to(REPO).as_posix() if rel.is_absolute()
               else rel.as_posix())
        trace = _git('log', '--oneline', '-1', '-S', name, '--',
                     'bootstrap/_scaffold/').stdout.strip()
        if not trace:
            raise Refusal(f'{key} traces to no commit touching the engine')
        was = _symbol_at(anchor, rel, kind, name)
        now = _symbol_at('HEAD', rel, kind, name)
        if was is None or now is None:
            raise Refusal(
                f'{key}: could not read {rel} at both {anchor[:12]} and HEAD. '
                'Its nature is undetermined, so nothing is asserted about it.')
        rows.append({
            'key': key, 'file': rel,
            'old': baseline[key]['digest'], 'new': new_digest,
            'span': A.digest_module(REPO / rel)[key].get('span'),
            'nature': 'docstring-only' if was == now else 'substantive',
            'commit': trace,
        })
    return rows


def apply_ast_baseline(rows: list[dict]) -> str:
    baseline = json.loads(BASELINE.read_text(encoding='utf-8'))
    before = len(baseline)
    for r in rows:
        baseline[r['key']]['digest'] = r['new']
        if r['span'] is not None:
            baseline[r['key']]['span'] = r['span']
    if len(baseline) != before:
        raise Refusal('the baseline symbol count would change -- that is a '
                      'full re-pin wearing a correction\'s clothes')
    BASELINE.write_text(json.dumps(baseline, indent=2, sort_keys=True) + '\n',
                        encoding='utf-8')
    return f'{len(rows)} digest(s) corrected; {before} symbols, unchanged'


def render_ast_baseline(rows: list[dict]) -> str:
    out = [f'{len(rows)} baseline digest(s) would be corrected.', '']
    for r in rows:
        out.append(f"  {r['key']}")
        out.append(f"      {r['file']}")
        out.append(f"      {r['old'][:16]} -> {r['new'][:16]}   [{r['nature']}]")
        out.append(f"      {r['commit'][:72]}")
    subs = sum(1 for r in rows if r['nature'] == 'substantive')
    out += ['', f'  {subs} substantive, {len(rows) - subs} docstring-only.',
            '  Every one traces to a landed commit, named above. Read those '
            'commit subjects:', '  they are what you are authorizing.']
    return '\n'.join(out)


# --------------------------------------------------------------------------
# correction: the install lockfile

def _read_lockfile() -> tuple[str, dict]:
    """The comment header (kept byte-for-byte) and the JSON body."""
    raw = LOCKFILE.read_text(encoding='utf-8')
    lines = raw.split('\n')
    n = 0
    while n < len(lines) and (lines[n].startswith('#') or not lines[n].strip()):
        n += 1
    return '\n'.join(lines[:n]), json.loads('\n'.join(lines[n:]))


def plan_lockfile() -> dict:
    sys.path.insert(0, str(REPO / 'bootstrap'))
    from _scaffold import config as C                        # noqa: PLC0415

    _header, doc = _read_lockfile()
    records = doc['files']
    remove = []
    for rec in records:
        dst = rec.get('dst')
        if not dst or (REPO / dst).exists():
            continue
        if _tracked(dst):
            raise Refusal(f'{dst}: absent from disk but still git-tracked. '
                          'That is not a sweep deletion; find out what it is.')
        remove.append(rec)

    recorded = {r.get('dst') for r in records}
    add = []
    for src_rel, dst_rel, verbatim in C._SKILLS_MAPPINGS:
        if not verbatim or dst_rel in recorded:
            continue
        sp, dp = REPO / 'templates' / src_rel, REPO / dst_rel
        if not dp.is_file():
            continue
        if not sp.is_file():
            raise Refusal(f'{dst_rel}: template templates/{src_rel} is missing')
        if sp.read_bytes() != dp.read_bytes():
            raise Refusal(
                f'{dst_rel} is NOT byte-identical to templates/{src_rel}. A '
                'verbatim record that disagrees with its template is a real '
                'defect, not a stale digest -- recording it would hide that.')
        digest = 'sha256:' + _sha(dp.read_bytes())
        add.append({'base_hash': digest, 'dst': dst_rel, 'hash': digest,
                    'src': src_rel, 'verbatim': True})
    return {'remove': remove, 'add': add, 'before': len(records)}


def apply_lockfile(plan: dict) -> str:
    header, doc = _read_lockfile()
    records = doc['files']
    if len(records) != plan['before']:
        raise Refusal('the lockfile changed since the plan was derived')
    # Match on `dst`, which is unique per record: the plan was built from a
    # separate read, so object identity cannot be used, and equality would
    # collapse two records that happened to be identical.
    doomed = {r['dst'] for r in plan['remove']}
    kept = [r for r in records if r.get('dst') not in doomed]
    doc['files'] = sorted(kept + plan['add'], key=lambda r: r.get('dst', ''))
    expected = plan['before'] - len(plan['remove']) + len(plan['add'])
    if len(doc['files']) != expected:
        raise Refusal(f'post-write count {len(doc["files"])} != planned {expected}')
    LOCKFILE.write_text(header + '\n' + json.dumps(doc, indent=2, sort_keys=True)
                        + '\n', encoding='utf-8')
    return (f'{len(plan["remove"])} removed, {len(plan["add"])} added; '
            f'{plan["before"]} -> {expected} records')


def render_lockfile(plan: dict) -> str:
    out = []
    if plan['remove']:
        out.append(f'{len(plan["remove"])} record(s) name files git no longer '
                   f'tracks, and would be REMOVED:')
        for r in plan['remove']:
            flag = '   [living_state flag on a deleted path]' if r.get('living_state') else ''
            out.append(f"    {r['dst']}{flag}")
    if plan['add']:
        out.append('')
        out.append(f'{len(plan["add"])} verbatim record(s) would be ADDED, each '
                   f'proven byte-identical to its template:')
        for a in plan['add']:
            out.append(f"    {a['dst']}  <- templates/{a['src']}")
    expected = plan['before'] - len(plan['remove']) + len(plan['add'])
    out += ['', f'  record count {plan["before"]} -> {expected}']
    return '\n'.join(out)


# --------------------------------------------------------------------------
# the one human step

CORRECTIONS = {
    'ast-baseline': (plan_ast_baseline, render_ast_baseline, apply_ast_baseline,
                     'the AST attestation baseline'),
    'lockfile': (plan_lockfile, render_lockfile, apply_lockfile,
                 'the install lockfile'),
}


def plan_digest(plan) -> str:
    """A digest over the plan's *content*, stable across equal plans."""
    return _sha(json.dumps(plan, sort_keys=True, default=str).encode())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog='correct_pinned_digests',
        description='Correct a Cairn trust artifact under one human '
                    'authorization: read the plan, type the checksum.')
    ap.add_argument('correction', choices=sorted(CORRECTIONS))
    ap.add_argument('--i-have-read-the-block-review', action='store_true',
                    help=argparse.SUPPRESS)
    ap.add_argument('--authorize', metavar='DIGEST8',
                    help='the first 8 characters of the plan digest, for a '
                         'non-interactive run. Without a terminal this is '
                         'REQUIRED -- a pipe must not be able to say yes.')
    args = ap.parse_args(argv)

    if not args.i_have_read_the_block_review:
        print(
            'REFUSE: this runner is BLOCKED by an External Security Review '
            '(Codex, 2026-08-27).\n'
            '  Seven blocking findings, two CRITICAL, each reproduced:\n'
            '    - --authorize lets any process perform the "human" step, and\n'
            '      removing it would not help; an agent can allocate a pty.\n'
            '    - the plan digest does not bind the complete preimage or\n'
            '      output: two materially different trees produced IDENTICAL\n'
            '      digests and apply wrote the unauthorized values.\n'
            '  Read dev/reviews/'
            '2026-08-27-external-security-review-correct-pinned-digests.md\n'
            '  Correct the artifacts by hand, under the runbooks, until the\n'
            '  redesign in that review\'s final section lands.',
            file=sys.stderr)
        return 2

    build, render, apply_, label = CORRECTIONS[args.correction]
    try:
        plan = build()
    except Refusal as exc:
        print(f'REFUSE: {exc}', file=sys.stderr)
        return 2

    empty = not plan if isinstance(plan, list) else not (plan['remove'] or plan['add'])
    if empty:
        print(f'{label}: nothing to correct.')
        return 0

    digest_a = plan_digest(plan)
    print(f'== correcting pinned digests: {label} ==\n')
    print(render(plan))
    print(f'\n  PLAN DIGEST: {digest_a}')
    print(f'  {"":13}^^^^^^^^ type these 8 characters to authorize\n')

    if args.authorize is not None:
        typed = args.authorize.strip()
    elif sys.stdin.isatty():
        typed = input('  authorize (8 chars, or anything else to abort): ').strip()
    else:
        print('REFUSE: stdin is not a terminal and --authorize was not given. '
              'A pipe must not be able to authorize a trust-artifact change.',
              file=sys.stderr)
        return 2

    if typed.lower() != digest_a[:8].lower():
        print('\nABORTED: that is not the plan digest. Nothing was written.',
              file=sys.stderr)
        return 1

    # Re-derive from the tree.  The operator authorized the state they READ;
    # if the tree moved while they were reading, this is where it is caught.
    try:
        fresh = build()
    except Refusal as exc:
        print(f'REFUSE on re-derivation: {exc}', file=sys.stderr)
        return 2
    digest_b = plan_digest(fresh)
    if digest_b != digest_a:
        print(f'\nREFUSE: the tree changed while you were reading.\n'
              f'  you authorized {digest_a[:16]}\n'
              f'  the tree is now {digest_b[:16]}\n'
              f'Nothing was written. Re-run and read the new plan.',
              file=sys.stderr)
        return 2

    try:
        summary = apply_(fresh)
    except Refusal as exc:
        print(f'REFUSE during apply: {exc}', file=sys.stderr)
        return 2
    print(f'\nAPPLIED: {summary}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
